"""Cross-cluster handoff: two small artifacts replace a full FUSE copy.

Copying ~10k files onto a *cross-cluster* FUSE mount is latency-bound
(every create/stat is a WAN round trip — observed ~1 h for a full
internal export to a sh02 path).  A ``git clone`` on the destination
host is one streaming pack over the backbone followed by local-disk
writes (minutes).  Handoff therefore writes ONLY two small artifacts
into the (possibly slow) destination dir:

  bootstrap.sh        one-click clone/pull + state restore + install.sh
  tofu_state.tar.gz   user state that never enters git (skills, memories,
                      seeded server_config.json)

  tofu_repo.tar.gz    OPTIONAL offline repo snapshot — when present,
                      bootstrap.sh extracts it instead of git-cloning
                      (destination hosts without git SSH keys)
The user carries the dir to the remote cluster (two small files copy
fine even over FUSE) and runs ``bash bootstrap.sh [dest]`` there.

Source-of-truth rule: by default only COMMITTED state transfers — the
remote side clones the pushed branch.  Internal ``--worktree`` opts into
mirroring the operator's CURRENT tree: the export copies dirty tracked
bytes and :func:`_stage_worktree_untracked` then stages the untracked,
non-gitignored source files the tar copy would otherwise skip (a dirty
tracked file importing an untracked module is the 2026-08-06 torn-
snapshot incident; for a handoff "latest state" means the whole tree).
The staged bytes re-run the internal sanitize pass before the snapshot-
push.  Personal mode still pushes the committed branch verbatim, so the
facade rejects ``--worktree`` there.  Without ``--worktree`` a dirty
worktree triggers a loud warning.

Internal mode targets the release repo (``_GIT_REPOS['internal']``, corp
GitLab, branch ``master``): colleagues clone it, so it must only ever
receive the SANITIZED export tree — never a raw source checkout (the raw
tree carries dev-only artifacts like ``export_pkg/_lists.py`` private
markers).  ``--push`` therefore exports locally (same-cluster dest = fast)
and snapshot-pushes that tree onto the release branch — the same technique
as the established manual pipeline (mixed reset onto origin/master, one
commit, fast-forward push).  Personal mode pushes the source branch
verbatim to the explicit ``--git-url`` (self-use repo, owner's call).
"""

