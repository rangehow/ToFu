# User state that git never tracks (gitignored in the source repo) but a
# self-use handoff must carry: agent skills + memories + error resolutions.
# ``.tofu/skills`` holds the project-runtime installs (``mtskills i`` / the
# Settings UI) — the half the owner-global ``data/skills`` store never covers.
_STATE_DIRS = ('data/skills', '.tofu/skills', 'data/memories', '.tofu/memories')
_STATE_FILES = ('.tofu/error_resolutions.json',)
# Personal mode additionally carries the MCP server config (contains the
# user's own tokens; internal mode strips it like the full export does).
_PERSONAL_EXTRA_CONFIG_FILES = ('mcp_servers.json',)

_BOOTSTRAP_TEMPLATE = '''#!/usr/bin/env bash
# tofu handoff bootstrap — generated by export.py --handoff (mode=__MODE__)
# Restore tofu on THIS host: extract the offline snapshot when present,
# else clone/pull the repo from git; then restore user state that never
# enters git and run the standard installer.
set -euo pipefail

__PROXY_BLOCK__
GIT_URL='__GIT_URL__'
BRANCH='__BRANCH__'
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DEST="${1:-$PWD/tofu}"

# Private repo? `export DEV_SANKUAI_TOKEN=...` before running.  The token
# authenticates this clone only; origin is reset to the clean URL after.
AUTH_URL="$GIT_URL"
if [ -n "${DEV_SANKUAI_TOKEN:-}" ] && [[ "$GIT_URL" == https://* ]]; then
  AUTH_URL="https://oauth2:${DEV_SANKUAI_TOKEN}@${GIT_URL#https://}"
fi

if [ -f "$SCRIPT_DIR/tofu_repo.tar.gz" ] && [ ! -d "$DEST/.git" ]; then
  # Offline snapshot: no git auth needed on this host (SSH keys may be
  # absent).  One streaming extract, then state restore + install as usual.
  echo "-> extracting offline snapshot tofu_repo.tar.gz -> $DEST"
  mkdir -p "$DEST"
  tar -xzf "$SCRIPT_DIR/tofu_repo.tar.gz" -C "$DEST"
elif [ -d "$DEST/.git" ]; then
  echo "-> updating existing clone: $DEST"
  git -C "$DEST" fetch origin "$BRANCH"
  git -C "$DEST" checkout "$BRANCH"
  git -C "$DEST" merge --ff-only "origin/$BRANCH"
else
  echo "-> cloning $GIT_URL ($BRANCH) -> $DEST"
  git clone --branch "$BRANCH" "$AUTH_URL" "$DEST"
  git -C "$DEST" remote set-url origin "$GIT_URL"
fi

echo "-> restoring user state (skills / memories / config)"
tar -xzf "$SCRIPT_DIR/tofu_state.tar.gz" -C "$DEST"

echo "-> running install.sh"
cd "$DEST"
./install.sh
echo "-> handoff complete: $DEST"
'''


def _git(args: list[str], timeout: int = 60) -> subprocess.CompletedProcess:
    return subprocess.run(['git', *args], cwd=str(ROOT),
                          capture_output=True, text=True, timeout=timeout)


def _current_branch() -> str | None:
    """Checked-out branch name; None on detached HEAD or git failure."""
    try:
        proc = _git(['rev-parse', '--abbrev-ref', 'HEAD'])
    except (OSError, subprocess.TimeoutExpired):
        return None
    if proc.returncode != 0:
        return None
    branch = proc.stdout.strip()
    return None if branch == 'HEAD' else branch


def _remote_branch_exists(git_url: str, branch: str) -> bool | None:
    """True/False when ls-remote succeeded, None when the remote is unreachable."""
    try:
        proc = _git(['ls-remote', '--heads', git_url, branch], timeout=30)
    except (OSError, subprocess.TimeoutExpired):
        return None
    if proc.returncode != 0:
        return None
    return bool(proc.stdout.strip())


def _push_head(git_url: str, branch: str) -> str | None:
    """Push HEAD to <git_url>/<branch>.  Returns None on success, else stderr tail."""
    try:
        proc = _git(['push', git_url, f'HEAD:refs/heads/{branch}'], timeout=300)
    except (OSError, subprocess.TimeoutExpired) as e:
        return str(e)
    if proc.returncode != 0:
        return (proc.stderr or proc.stdout).strip()[-500:]
    return None


# Internal handoff --push exports here before snapshot-pushing: the
# established release dest, same-cluster (fast) and persistent (.git
# survives across releases, so repeat pushes stay incremental).
_INTERNAL_EXPORT_DEST = ROOT.parent / 'tofu-meituan'


def _git_identity(dest: Path):
    """Copy commit identity from the source repo into <dest> (fresh inits)."""
    email = _git(['config', 'user.email']).stdout.strip() or 'tofu-export@localhost'
    name = _git(['config', 'user.name']).stdout.strip() or 'tofu-export'
    for key, value in (('user.email', email), ('user.name', name)):
        subprocess.run(['git', 'config', key, value], cwd=str(dest),
                       capture_output=True, text=True)


def _snapshot_push(export_dest: Path, git_url: str, branch: str) -> str | None:
    """Snapshot-push the exported tree onto <git_url>/<branch> (fast-forward).

    Mixed reset onto origin/<branch>: index takes the remote tree, worktree
    keeps the export, ``add -A`` stages the diff as ONE commit — remote
    history is preserved and the push never needs force.  Returns None on
    success (or nothing-to-push), else an error tail.
    """
    def run(args: list[str], timeout: int = 300) -> subprocess.CompletedProcess:
        return subprocess.run(['git', *args], cwd=str(export_dest),
                              capture_output=True, text=True, timeout=timeout)

    try:
        if not (export_dest / '.git').is_dir():
            proc = run(['init'])
            if proc.returncode != 0:
                return (proc.stderr or proc.stdout).strip()[-500:]
        _git_identity(export_dest)
        run(['remote', 'remove', 'origin'])  # absent on fresh init — fine
        proc = run(['remote', 'add', 'origin', git_url])
        if proc.returncode != 0:
            return (proc.stderr or proc.stdout).strip()[-500:]
        fetched = run(['fetch', 'origin', branch])
        if fetched.returncode == 0:
            run(['symbolic-ref', 'HEAD', f'refs/heads/{branch}'])
            proc = run(['reset', f'origin/{branch}'])
        else:
            # First release: remote has no branch yet — start the history.
            proc = run(['checkout', '-B', branch])
        if proc.returncode != 0:
            return (proc.stderr or proc.stdout).strip()[-500:]
        run(['add', '-A'])
        if not run(['status', '--porcelain']).stdout.strip():
            return None  # tree identical to remote tip — nothing to push
        ts = datetime.now().strftime('%Y-%m-%d %H:%M')
        proc = run(['commit', '-m', f'Export (internal) — {ts}'])
        if proc.returncode != 0:
            return (proc.stderr or proc.stdout).strip()[-500:]
        proc = run(['push', 'origin', branch])
        if proc.returncode != 0:
            return (proc.stderr or proc.stdout).strip()[-500:]
    except (OSError, subprocess.TimeoutExpired) as e:
        return str(e)
    return None


def _stage_worktree_untracked(src: Path, dest: Path) -> int:
    """Copy untracked, non-gitignored FILES from <src> into <dest>; return count.

    ``--worktree`` internal handoffs must mirror the operator's current
    tree, but the export's tar copy still skips untracked files ("the
    published tree mirrors committed source" — a PUBLIC-release rule that
    keeps uncommitted files out of the opensource CI).  For a handoff the
    skip would tear the snapshot exactly like the 2026-08-06 incident
    (dirty tracked file imports an untracked module that did not ship), so
    stage those files here after the export and let the snapshot-push
    carry them.  Stray untracked ROOT dirs stay excluded (agent scratch —
    same rule as the tar copy).  Callers must re-run the mode sanitize
    pass afterwards: staged bytes bypassed the export's own pass.
    """
    staged = 0
    for rel in sorted(_untracked_nested_files(src, _untracked_root_dirs(src))):
        source = src / rel
        if not source.is_file():
            continue
        target = dest / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, target)
        staged += 1
    return staged


# Fixed archive timestamp: deterministic bytes without tripping tar's
# "implausibly old timestamp" warnings that mtime=0 (1970) causes.
_TAR_MTIME = 1577836800  # 2020-01-01T00:00:00Z


def _normalized(ti: tarfile.TarInfo) -> tarfile.TarInfo:
    # Deterministic archives: equivalent inputs -> equivalent output bytes.
    ti.mtime = _TAR_MTIME
    ti.uid = ti.gid = 0
    ti.uname = ti.gname = ''
    return ti


def _add_path(tf: tarfile.TarFile, fs_path: Path, arcname: str):
    if fs_path.is_dir():
        tf.addfile(_normalized(tf.gettarinfo(str(fs_path), arcname)))
        for child in sorted(fs_path.iterdir(), key=lambda p: p.name):
            _add_path(tf, child, f'{arcname}/{child.name}')
    else:
        ti = _normalized(tf.gettarinfo(str(fs_path), arcname))
        with open(fs_path, 'rb') as f:
            tf.addfile(ti, f)


def _stage_config(mode: str, staging: Path) -> list[Path]:
    """Stage data/config/server_config.json into <staging>; return staged roots."""
    src_config = ROOT / 'data' / 'config' / 'server_config.json'
    if mode == 'internal':
        # Reuse the full export's seeding: whitelisted shared keys only,
        # providers filtered to the internal set.
        _seed_internal_config(staging)
        _stage_portable_mcp_config(staging)
        seeded = staging / 'data' / 'config' / 'server_config.json'
        return [staging / 'data'] if seeded.exists() else []
    # personal: self-use — full config + personal MCP tokens carry over.
    staged_cfg = staging / 'data' / 'config'
    staged_cfg.mkdir(parents=True, exist_ok=True)
    staged = False
    if src_config.exists():
        staged_cfg.joinpath('server_config.json').write_bytes(src_config.read_bytes())
        staged = True
    for name in _PERSONAL_EXTRA_CONFIG_FILES:
        extra = ROOT / 'data' / 'config' / name
        if extra.exists():
            staged_cfg.joinpath(name).write_bytes(extra.read_bytes())
            staged = True
    return [staging / 'data'] if staged else []


def _write_state_tarball(tar_path: Path, mode: str):
    """Write tofu_state.tar.gz (deterministic: sorted, normalized metadata)."""
    with tempfile.TemporaryDirectory(prefix='tofu-handoff-') as tmp:
        staged_roots = _stage_config(mode, Path(tmp))
        with open(tar_path, 'wb') as raw:
            with gzip.GzipFile(filename='', mode='wb', fileobj=raw, mtime=0) as gz:
                with tarfile.open(fileobj=gz, mode='w',
                                  format=tarfile.PAX_FORMAT) as tf:
                    for rel in _STATE_DIRS + _STATE_FILES:
                        src = ROOT / rel
                        if src.exists():
                            _add_path(tf, src, rel)
                    for staged in staged_roots:
                        # The staging root IS data/ — add its children under
                        # their real arcnames so state dirs and config merge.
                        for child in sorted(staged.iterdir(), key=lambda p: p.name):
                            _add_path(tf, child, f'data/{child.name}')


def _bootstrap_script(mode: str, git_url: str, branch: str) -> str:
    proxy_block = ''
    src_config = ROOT / 'data' / 'config' / 'server_config.json'
    if src_config.exists():
        try:
            cfg = json.loads(src_config.read_text(encoding='utf-8'))
        except (json.JSONDecodeError, OSError) as e:
            logger.warning('Failed to read server_config.json for bootstrap proxy: %s', e)
            cfg = {}
        cfg = _with_internal_proxy_default(cfg, mode)
        env_lines, _, _ = _proxy_env_lines_from_config(cfg)
        if env_lines:
            proxy_block = '# Corp proxy for git clone / conda / pip on this host.\n' + \
                          '\n'.join(env_lines) + '\n\n'
    script = _BOOTSTRAP_TEMPLATE
    for placeholder, value in (
        ('__MODE__', mode),
        ('__GIT_URL__', git_url),
        ('__BRANCH__', branch),
        ('__PROXY_BLOCK__', proxy_block),
    ):
        script = script.replace(placeholder, value)
    return script


def run_handoff(mode: str, dest_dir: Path, git_url: str | None = None,
                push: bool = False, dry_run: bool = False,
                worktree: bool = False):
    """Write bootstrap.sh + tofu_state.tar.gz for a cross-cluster handoff.

    Fatal conditions raise SystemExit (mirrors export facade behavior).
    """
    if mode == 'opensource':
        raise SystemExit(
            f'{C_RED}--handoff is not available for opensource mode: public '
            f'releases already transfer via GitHub and carry no user state.{C_END}')
    if worktree and mode != 'internal':
        raise SystemExit(
            f'{C_RED}--handoff (personal) pushes the committed branch '
            f'verbatim; --worktree is meaningless there.{C_END}')

    release_cfg = _GIT_REPOS.get('internal') or {}
    if mode == 'internal':
        # Release repo + release branch: colleagues clone master, which must
        # hold the sanitized export snapshot — never a raw source checkout.
        git_url = git_url or (release_cfg.get('remotes') or [{}])[0].get('url')
        branch = release_cfg.get('branch', 'master')
    else:
        if not git_url:
            raise SystemExit(
                f'{C_RED}--handoff (personal) needs --git-url — a repo the '
                f'remote host can clone.{C_END}')
        branch = _current_branch()
        if not branch:
            raise SystemExit(
                f'{C_RED}--handoff needs a checked-out branch (detached HEAD '
                f'detected) — the remote side clones a branch.{C_END}')
    if not git_url:
        raise SystemExit(f'{C_RED}--handoff: no git URL configured.{C_END}')

    # Preview must return before export, push, remote probes, or artifact writes.
    if dry_run:
        if push:
            action = 'export and snapshot-push' if mode == 'internal' else 'push HEAD'
            print(f"  {C_CYAN}Handoff (dry run): would {action} → "
                  f"{git_url} ({branch}){C_END}")
        print(f"  {C_CYAN}🤝 Handoff (dry run): would write bootstrap.sh + "
              f"tofu_state.tar.gz → {dest_dir}{C_END}")
        return

    dirty = _dirty_tracked_files(ROOT)
    if dirty and worktree:
        print(f"  {C_CYAN}ℹ --worktree: {len(dirty)} dirty tracked file(s) + "
              f"untracked source files WILL ship — the release branch mirrors "
              f"your current tree.{C_END}")
    elif dirty:
        print(f"  {C_YELLOW}⚠ {len(dirty)} tracked file(s) have uncommitted "
              f"changes — handoff transfers COMMITTED state only.{C_END}")
        print(f"  {C_DIM}  commit first, or the remote clone will be behind "
              f"your worktree.{C_END}")
        logger.info('[Handoff] dirty worktree: %d tracked files differ from HEAD',
                    len(dirty))

    if push:
        if mode == 'internal':
            # Snapshot release: fresh sanitized export (same-cluster dest =
            # fast), then snapshot-push onto the release branch.
            from export_pkg._orchestrate import export_project
            print(f"  {C_DIM}Exporting internal snapshot → "
                  f"{_INTERNAL_EXPORT_DEST}{C_END}")
            export_project('internal', _INTERNAL_EXPORT_DEST, push=False,
                           worktree=worktree)
            if worktree:
                staged = _stage_worktree_untracked(ROOT, _INTERNAL_EXPORT_DEST)
                if staged:
                    print(f"  {C_CYAN}ℹ --worktree: staged {staged} untracked "
                          f"source file(s) the committed-source rule skips{C_END}")
                    # Staged bytes bypassed the export's sanitize pass.
                    _post_copy_sanitize(_INTERNAL_EXPORT_DEST, 'internal')
            err = _snapshot_push(_INTERNAL_EXPORT_DEST, git_url, branch)
            action = f'snapshot-pushed {_INTERNAL_EXPORT_DEST}'
        else:
            err = _push_head(git_url, branch)
            action = 'pushed HEAD'
        if err:
            raise SystemExit(
                f'{C_RED}--handoff push failed ({git_url} {branch})\n'
                f'{err}{C_END}')
        print(f"  {C_GREEN}⬆ {action} → {git_url} ({branch}){C_END}")
    else:
        remote_state = _remote_branch_exists(git_url, branch)
        if remote_state is None:
            print(f"  {C_YELLOW}⚠ could not reach {git_url} from here — "
                  f"continuing anyway (the remote host may still reach it).{C_END}")
        elif not remote_state:
            print(f"  {C_YELLOW}⚠ branch '{branch}' is not on {git_url} yet — "
                  f"the bootstrap clone will fail unless you release first "
                  f"(or re-run with --push).{C_END}")
        elif mode == 'internal':
            print(f"  {C_DIM}Bootstrap will clone {branch} as of the last "
                  f"release push — re-run with --push to release now.{C_END}")

    dest_dir.mkdir(parents=True, exist_ok=True)
    tar_path = dest_dir / 'tofu_state.tar.gz'
    _write_state_tarball(tar_path, mode)

    script_path = dest_dir / 'bootstrap.sh'
    script_path.write_text(_bootstrap_script(mode, git_url, branch),
                           encoding='utf-8')
    script_path.chmod(0o755)

    size_kb = max(1, tar_path.stat().st_size // 1024)
    print(f"  {C_GREEN}🤝 Handoff ready → {dest_dir}{C_END}")
    print(f"     {C_DIM}bootstrap.sh (clone {branch} from git + restore state + "
          f"install)  ·  tofu_state.tar.gz ({size_kb} KiB: skills, memories, "
          f"config){C_END}")
    print(f"  {C_DIM}Next: on the remote host run "
          f"`bash {dest_dir}/bootstrap.sh [dest-dir]` — no cross-cluster "
          f"file copy needed.{C_END}")
    print(f"  {C_DIM}No git SSH key on the remote host? Drop a tofu_repo.tar.gz "
          f"(`tar -czf ... -C <export-dest> .`) beside bootstrap.sh and it "
          f"extracts offline instead of cloning.{C_END}")
    logger.info('[Handoff] wrote %s and %s (mode=%s, branch=%s)',
                script_path, tar_path, mode, branch)
