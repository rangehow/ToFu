#!/usr/bin/env python3
"""Freeze the CPython ``str`` case and class predicates the MCP catalog search uses.

``lib/mcp/tool_search.py``, ``progressive.py`` and ``connector_guidance.py``
casefold, lowercase and tokenize with ``\\w``; the Rust port must answer with
CPython's Unicode database, not Rust's. Writes
``packages/tofu-mcp/src/generated_pyunicode.rs``; ``--check`` fails when the
committed file differs (``tests/mcp_protocol/test_rust_catalog_parity.py``).
"""
from __future__ import annotations

import argparse
from pathlib import Path
import unicodedata

ROOT = Path(__file__).resolve().parents[3]
OUTPUT = ROOT / 'packages' / 'tofu-mcp' / 'src' / 'generated_pyunicode.rs'


def _rust_string(value: str) -> str:
    return '"' + ''.join(f'\\u{{{ord(char):x}}}' for char in value) + '"'


def _ranges(predicate) -> list[tuple[int, int]]:
    ranges: list[tuple[int, int]] = []
    for codepoint in range(0x110000):
        if not predicate(chr(codepoint)):
            continue
        if ranges and ranges[-1][1] == codepoint - 1:
            ranges[-1] = (ranges[-1][0], codepoint)
        else:
            ranges.append((codepoint, codepoint))
    return ranges


def _mapping(name: str, method) -> list[str]:
    lines = [f'pub fn {name}(value: char) -> Option<&\'static str> {{', '    match value {']
    for codepoint in range(0x110000):
        char = chr(codepoint)
        if 0xD800 <= codepoint <= 0xDFFF:
            continue
        mapped = method(char)
        if mapped != char:
            lines.append(f"        '\\u{{{codepoint:x}}}' => Some({_rust_string(mapped)}),")
    lines += ['        _ => None,', '    }', '}', '']
    return lines


def _render() -> str:
    alnum = _ranges(lambda char: char.isalnum())
    version = tuple(int(part) for part in unicodedata.unidata_version.split('.'))
    return '\n'.join([
        '//! @generated by packages/tofu-mcp/scripts/gen_pyunicode.py; do not edit.',
        '//! CPython `str.casefold`, per-character `str.lower` and `str.isalnum`.',
        '',
        f'pub const PYTHON_UNICODE_VERSION: (u16, u16, u16) = ({version[0]}, {version[1]}, {version[2]});',
        '',
        *_mapping('casefold_mapping', str.casefold),
        *_mapping('lower_mapping', str.lower),
        'pub fn is_alnum(value: char) -> bool {',
        '    matches!(value,',
        '        ' + '\n        | '.join(
            f"'\\u{{{start:x}}}'..='\\u{{{end:x}}}'" if start != end else f"'\\u{{{start:x}}}'"
            for start, end in alnum),
        '    )',
        '}',
        '',
    ])


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    rendered = _render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding='utf-8') != rendered:
            raise SystemExit(f'{OUTPUT.relative_to(ROOT)} is stale')
        return 0
    OUTPUT.write_text(rendered, encoding='utf-8')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
