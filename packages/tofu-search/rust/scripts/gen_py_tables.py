"""Generate ``src/py_tables.rs`` from the interpreter and BeautifulSoup in use.

The URL, citation and HTML kernels mirror CPython's ``re`` ``\\d`` and
``IGNORECASE`` folding, ``html.unescape`` and BeautifulSoup's entity and
numeric-reference tables. Those are data owned by the interpreter/library, so
they are exported from them rather than transcribed by hand. The existing
``unicode_tables.rs`` (lexical kernels) is produced separately by
``gen_unicode_tables.py``.

Usage: python3 gen_py_tables.py [--check]
"""

import html
import html.entities
import re
import sys
import unicodedata
from pathlib import Path

from bs4.dammit import EntitySubstitution, UnicodeDammit

OUT = Path(__file__).resolve().parents[1] / 'src' / 'py_tables.rs'
MAX = sys.maxunicode + 1


def _ranges(pred):
    out, start = [], None
    for cp in range(MAX):
        hit = not (0xD800 <= cp <= 0xDFFF) and pred(chr(cp))
        if hit and start is None:
            start = cp
        elif not hit and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, MAX - 1))
    return out


def _rust_str(value):
    return '"' + ''.join(
        c if (0x20 <= ord(c) < 0x7F and c not in '"\\') else f'\\u{{{ord(c):x}}}'
        for c in value) + '"'


def _range_table(name, doc, ranges):
    body = '\n'.join(f'    (0x{lo:X}, 0x{hi:X}),' for lo, hi in ranges)
    return f'/// {doc}\npub static {name}: &[(u32, u32)] = &[\n{body}\n];\n'


def _map_table(name, doc, items):
    body = '\n'.join(f'    ({_rust_str(k)}, {_rust_str(v)}),' for k, v in sorted(items))
    return f'/// {doc}\npub static {name}: &[(&str, &str)] = &[\n{body}\n];\n'


def render():
    digit = re.compile(r'\d')
    decimal = _ranges(lambda c: digit.fullmatch(c) is not None)
    folds = []
    for letter in 'abcdefghijklmnopqrstuvwxyz':
        pattern = re.compile(letter, re.IGNORECASE)
        extra = [cp for cp in range(MAX) if not (0xD800 <= cp <= 0xDFFF)
                 and chr(cp) not in (letter, letter.upper())
                 and pattern.fullmatch(chr(cp))]
        for cp in extra:
            folds.append((cp, letter))
    fold_body = '\n'.join(f"    (0x{cp:X}, '{letter}')," for cp, letter in sorted(folds))
    invalid_charrefs = sorted(html._invalid_charrefs.items())
    invalid_codepoints = sorted(html._invalid_codepoints)
    windows_1252 = sorted((k, v.decode('utf8')) for k, v in UnicodeDammit.WINDOWS_1252_TO_UTF8.items()
                          if 0x80 <= k <= 0x9F)
    import bs4
    parts = [
        '// @generated by rust/scripts/gen_py_tables.py; do not edit.\n'
        f'// Python {sys.version.split()[0]}, Unicode {unicodedata.unidata_version}, '
        f'beautifulsoup4 {bs4.__version__}.\n',
        _range_table('DECIMAL', '`re` `\\d` for `str` patterns (Unicode Nd).', decimal),
        '/// Non-ASCII code points an ASCII letter matches under `re.IGNORECASE`.\n'
        f'pub static IGNORECASE_EXTRA: &[(u32, char)] = &[\n{fold_body}\n];\n',
        _map_table('HTML5_ENTITIES', '`html.entities.html5` (names may end with `;`).',
                   html.entities.html5.items()),
        _map_table('BS4_ENTITIES', 'BeautifulSoup `EntitySubstitution.HTML_ENTITY_TO_CHARACTER`.',
                   EntitySubstitution.HTML_ENTITY_TO_CHARACTER.items()),
        '/// `html._invalid_charrefs`.\npub static INVALID_CHARREFS: &[(u32, &str)] = &[\n'
        + '\n'.join(f'    (0x{k:X}, {_rust_str(v)}),' for k, v in invalid_charrefs) + '\n];\n',
        '/// `html._invalid_codepoints`.\npub static INVALID_CODEPOINTS: &[u32] = &[\n'
        + '\n'.join(f'    0x{k:X},' for k in invalid_codepoints) + '\n];\n',
        '/// BeautifulSoup `UnicodeDammit.WINDOWS_1252_TO_UTF8` for C1 references.\n'
        'pub static WINDOWS_1252_C1: &[(u32, &str)] = &[\n'
        + '\n'.join(f'    (0x{k:X}, {_rust_str(v)}),' for k, v in windows_1252) + '\n];\n',
        '/// BeautifulSoup `UnicodeDammit.ENUMERATED_NONCHARACTERS`.\n'
        'pub static ENUMERATED_NONCHARACTERS: &[u32] = &[\n'
        + '\n'.join(f'    0x{k:X},' for k in sorted(UnicodeDammit.ENUMERATED_NONCHARACTERS))
        + '\n];\n',
    ]
    return '\n'.join(parts)


def main():
    text = render()
    if '--check' in sys.argv:
        if OUT.read_text() != text:
            sys.stderr.write(f'{OUT} is stale; run {Path(__file__).name}\n')
            return 1
        return 0
    OUT.write_text(text)
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
