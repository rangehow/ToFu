"""Generate ``src/unicode_tables.rs`` from CPython's own ``str`` predicates.

The native kernels must classify characters exactly as the Python oracle does:
``re`` ``\\w``/``\\s``, ``str.isalnum``/``isalpha``/``isdigit``/``isspace``,
``str.casefold`` and ``str.lower``. Those follow the interpreter's bundled
Unicode database, not the Rust standard library's (newer) tables, so the tables
are exported from the interpreter that runs this script.

Usage: python3 gen_unicode_tables.py [--check]
"""

import sys
import unicodedata
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / 'src' / 'unicode_tables.rs'
MAX = sys.maxunicode + 1
# Word_Break MidLetter/MidNumLet/Single_Quote: case-ignorable by definition.
_MID_LETTER = {0x27, 0x2E, 0x3A, 0xB7, 0x387, 0x55F, 0x5F4, 0x2018, 0x2019,
               0x2024, 0x2027, 0xFE13, 0xFE52, 0xFE55, 0xFF07, 0xFF0E, 0xFF1A}


def _ranges(pred):
    out, start = [], None
    for cp in range(MAX):
        if 0xD800 <= cp <= 0xDFFF:
            hit = False
        else:
            hit = pred(chr(cp))
        if hit and start is None:
            start = cp
        elif not hit and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, MAX - 1))
    return out


def _table(name, ranges):
    body = ''.join(f'    (0x{a:X}, 0x{b:X}),\n' for a, b in ranges)
    return f'pub static {name}: &[(u32, u32)] = &[\n{body}];\n\n'


def _mapping(name, fn):
    rows = []
    for cp in range(MAX):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        char = chr(cp)
        mapped = fn(char)
        if mapped != char:
            literal = ''.join(f'\\u{{{ord(c):X}}}' for c in mapped)
            rows.append(f'    (0x{cp:X}, "{literal}"),\n')
    return f'pub static {name}: &[(u32, &str)] = &[\n{"".join(rows)}];\n\n'


def _cased(char):
    return char.lower() != char or char.upper() != char or char.islower() or char.isupper()


def _case_ignorable(char):
    return (unicodedata.category(char) in {'Mn', 'Me', 'Cf', 'Lm', 'Sk'}
            or ord(char) in _MID_LETTER)


def render():
    return (
        '// @generated by scripts/gen_unicode_tables.py from CPython '
        f'{sys.version_info.major}.{sys.version_info.minor} '
        f'(unicodedata {unicodedata.unidata_version}). Do not edit.\n\n'
        f'pub const UNIDATA_VERSION: &str = "{unicodedata.unidata_version}";\n\n'
        + _table('ALPHA', _ranges(str.isalpha))
        + _table('ALNUM', _ranges(str.isalnum))
        + _table('DIGIT', _ranges(str.isdigit))
        + _table('SPACE', _ranges(str.isspace))
        + _table('CASED', _ranges(_cased))
        + _table('CASE_IGNORABLE', _ranges(_case_ignorable))
        + _table('ASSIGNED', _ranges(lambda c: unicodedata.category(c) != 'Cn'))
        + _mapping('CASEFOLD', str.casefold)
        + _mapping('LOWER', str.lower)
    )


def main():
    text = render()
    if '--check' in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding='utf-8') != text:
            sys.stderr.write(f'{OUT} is stale; run {Path(__file__).name}\n')
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding='utf-8')
    return 0


if __name__ == '__main__':
    sys.exit(main())
