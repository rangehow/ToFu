#!/usr/bin/env python3
"""Freeze the ICU default simple-case-fold table for both storage authorities.

The table is the case-insensitive containment contract of the legacy LIKE
probes (``log_aggregate.query``): Tofu-DB folds with the Rust copy and the SQL
authority registers the Python copy as an explicit SQLite function, so neither
authority depends on whether its linked libsqlite3 was built with ICU.
"""

from __future__ import annotations

import argparse
import ctypes
import ctypes.util
from pathlib import Path
import re
import sys


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "packages" / "tofu-db" / "src" / "generated_unicode_simple_fold.rs"
PYTHON_OUTPUT = (
    ROOT / "lib" / "storage_authority_sql" / "generated_unicode_simple_fold.py"
)
# --check exit status when neither this interpreter's SQLite nor its
# environment provides ICU: there is no reference table to compare with, so
# drift was not checked.
ICU_UNAVAILABLE_EXIT = 3


class IcuUnavailable(RuntimeError):
    pass


def _icu_symbol(library: ctypes.CDLL, base: str):
    """Resolve unversioned or ELF/macOS version-suffixed ICU exports."""
    candidates = [base]
    library_name = str(library._name)  # noqa: SLF001 - ctypes exposes no public name
    versions = [int(value) for value in re.findall(r"(?:so\.|\.)(\d+)", library_name)]
    candidates.extend(f"{base}_{version}" for version in versions)
    candidates.extend(f"{base}_{version}" for version in range(99, 49, -1))
    for candidate in dict.fromkeys(candidates):
        try:
            return getattr(library, candidate)
        except AttributeError:
            continue
    raise RuntimeError(f"linked ICU library does not export {base}")


def _load_icu() -> ctypes.CDLL:
    """Load the interpreter environment's ICU, never the OS one.

    find_library("icuuc") resolves the OS ICU (Unicode 6.2 on this host),
    while the conda environment behind the storage authority ships ICU 78
    (Unicode 17). Prefer the libicuuc the interpreter's _sqlite3 links; a
    libsqlite3 built without ICU (conda-forge libsqlite >= 3.53) falls back to
    the same environment's ICU installation.
    """
    import _sqlite3  # noqa: PLC0415 - resolves the interpreter's own build
    import subprocess  # noqa: PLC0415

    ldd = subprocess.run(
        ["ldd", _sqlite3.__file__], check=True, capture_output=True, text=True
    ).stdout
    match = re.search(r"libicuuc\.so\.\d+ => (\S+)", ldd)
    if match:
        return ctypes.CDLL(match.group(1))
    installed = sorted(
        (Path(sys.base_prefix) / "lib").glob("libicuuc.so.[0-9]*"),
        key=lambda path: len(path.name),
    )
    if not installed:
        raise IcuUnavailable(
            "neither _sqlite3 nor the interpreter environment provides libicuuc")
    return ctypes.CDLL(str(installed[0]))


def _mappings() -> tuple[tuple[int, int, int], list[tuple[int, int]]]:
    library = _load_icu()
    fold = _icu_symbol(library, "u_foldCase")
    fold.argtypes = [ctypes.c_int32, ctypes.c_uint32]
    fold.restype = ctypes.c_int32
    unicode_version = (ctypes.c_uint8 * 4)()
    get_unicode_version = _icu_symbol(library, "u_getUnicodeVersion")
    get_unicode_version.argtypes = [ctypes.POINTER(ctypes.c_uint8)]
    get_unicode_version.restype = None
    get_unicode_version(unicode_version)

    mappings = []
    for codepoint in range(0x110000):
        if 0xD800 <= codepoint <= 0xDFFF:
            continue
        mapped = int(fold(codepoint, 0))  # U_FOLD_CASE_DEFAULT
        if mapped != codepoint:
            mappings.append((codepoint, mapped))
    version = tuple(int(value) for value in unicode_version[:3])
    return version, mappings


def _render(version: tuple[int, int, int], mappings: list[tuple[int, int]]) -> str:
    rows = [f"    (0x{source:06X}, 0x{target:06X})," for source, target in mappings]
    return "\n".join([
        "//! @generated by scripts/gen_tofudb_unicode_simple_fold.py; do not edit.",
        "",
        "/// ICU default simple case folding used by SQLite ENABLE_ICU LIKE.",
        "#[cfg(test)]",
        f"pub(crate) const ICU_UNICODE_VERSION: (u8, u8, u8) = {version!r};",
        "#[cfg(test)]",
        f"pub(crate) const SIMPLE_CASE_FOLDING_COUNT: usize = {len(mappings)};",
        "pub(crate) const SIMPLE_CASE_FOLDING: &[(u32, u32)] = &[",
        *rows,
        "];",
        "",
        "pub(crate) fn simple_case_fold(codepoint: u32) -> u32 {",
        "    SIMPLE_CASE_FOLDING",
        "        .binary_search_by_key(&codepoint, |entry| entry.0)",
        "        .map(|index| SIMPLE_CASE_FOLDING[index].1)",
        "        .unwrap_or(codepoint)",
        "}",
        "",
        "// --check detects linked-ICU Unicode-data drift.",
        "",
    ])


def _render_python(
    version: tuple[int, int, int], mappings: list[tuple[int, int]],
) -> str:
    rows = [f"    0x{source:06X}: 0x{target:06X}," for source, target in mappings]
    return "\n".join([
        '"""@generated by scripts/gen_tofudb_unicode_simple_fold.py; do not edit.',
        "",
        "ICU default simple case folding (one code point to one code point), the",
        "case-insensitive LIKE containment contract shared with Tofu-DB's",
        "generated_unicode_simple_fold.rs.",
        '"""',
        "",
        f"ICU_UNICODE_VERSION = {version!r}",
        "SIMPLE_CASE_FOLDING: dict[int, int] = {",
        *rows,
        "}",
        "",
        "",
        "def simple_case_fold(text: str) -> str:",
        "    return text.translate(SIMPLE_CASE_FOLDING)",
        "",
    ])


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        version, mappings = _mappings()
    except IcuUnavailable as unavailable:
        print(f"{unavailable}: no ICU to freeze or check against", file=sys.stderr)
        return ICU_UNAVAILABLE_EXIT
    outputs = {
        OUTPUT: _render(version, mappings),
        PYTHON_OUTPUT: _render_python(version, mappings),
    }
    if args.check:
        for path, rendered in outputs.items():
            if not path.exists() or path.read_text(encoding="utf-8") != rendered:
                raise SystemExit(f"{path.relative_to(ROOT)} is stale for the linked ICU")
        return 0
    for path, rendered in outputs.items():
        path.write_text(rendered, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
