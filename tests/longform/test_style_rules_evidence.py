"""The shipped style rules are justified by committed evidence.

``lib/longform/documents/style_rules.json`` is generated by
``evaluations/paper_style_corpus`` (``distill.py`` → ``validate.py rules
--write``). This specification keeps the contract from acceptance check 3:
every rule cites a *supported* corpus finding, metric lints are measurable and
do not fail the typical top paper, and an A/B-testable rule ships only if it
won its blind A/B.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

import pytest

from lib.longform.documents import style_metrics
from lib.longform.documents.rules import lint_text, rules_for

pytestmark = pytest.mark.unit

ROOT = Path(__file__).resolve().parents[2]
STYLE = json.loads((ROOT / 'lib/longform/documents/style_rules.json').read_text())['rules']
CORPUS = ROOT / 'evaluations/paper_style_corpus'
FINDINGS = json.loads((CORPUS / 'findings.json').read_text())['contrasts']
RULE_AB = json.loads((CORPUS / 'validation_rule_ab.json').read_text())['rules']
SELECTION = json.loads((CORPUS / 'validation_drafts_selection.json').read_text())
HARMFUL = set(SELECTION['harmful'])
CANDIDATES = {c['id']: c for c in json.loads((CORPUS / 'candidates.json').read_text())['candidates']}


def test_every_rule_cites_a_supported_finding():
    supported = {r['feature'] for r in FINDINGS['top_vs_accepted'] if r.get('supported')}
    for rule in STYLE:
        cited = set(re.findall(r'top_vs_accepted/(\w+)', rule['evidence']))
        assert cited and cited <= supported, rule['id']
        assert rule['id'].startswith('paper.style.') and rule['kind'] in ('lint', 'checklist')
        assert rule['origin'] and rule['text']


def test_testable_rules_won_their_blind_ab_and_losers_are_absent():
    shipped = {rule['id'] for rule in STYLE}
    for rule_id, verdict in RULE_AB.items():
        assert (rule_id in shipped) == (verdict['keep'] and rule_id not in HARMFUL), rule_id
        if verdict['keep']:
            assert verdict['rule_preferred_both_orders'] > verdict['baseline_preferred_both_orders']
    for rule_id in shipped:
        assert rule_id in RULE_AB or not CANDIDATES[rule_id]['testable_on_abstract_intro'], rule_id


def test_rules_and_outlines_whose_ablation_showed_harm_are_not_shipped():
    # validate.py drafts --ablate: B without the item preferred on more held-out
    # drafts than full B (style-blind pipeline judge) means the item is removed.
    data = json.loads((ROOT / 'lib/longform/documents/style_rules.json').read_text())
    ablated = {key.split('/')[0][len('ablate:'):] for key in SELECTION['comparisons']
               if key.startswith('ablate:')}
    assert {rule['id'] for rule in STYLE} <= ablated
    assert not HARMFUL & {rule['id'] for rule in STYLE}
    assert bool(data.get('outlines')) == ('outlines' not in HARMFUL)
    for key, row in SELECTION['comparisons'].items():
        if key.startswith('ablate:') and row and not key.endswith('drafts_only'):
            item = key.split('/')[0][len('ablate:'):]
            assert (item in HARMFUL) == (row['candidate_preferred'] > row['baseline_preferred']), item


def test_metric_rules_are_measurable_and_reach_the_lint_gate():
    metric_rules = [rule for rule in STYLE if rule.get('metric')]
    paper_rules = rules_for('paper')
    for rule in metric_rules:
        metric = rule['metric']
        assert metric['name'] in style_metrics.METRICS and metric['op'] in ('<=', '>=')
        assert metric['section'] in ('abstract', 'introduction', 'related_work', 'method',
                                     'experiments', 'conclusion', 'limitations')
        assert any(r.id == rule['id'] for r in paper_rules)


def test_a_data_metric_lint_flags_nominal_prose_and_passes_verbal_prose(tmp_path, monkeypatch):
    from lib.longform.documents import rules as rules_mod
    data_file = tmp_path / 'style_rules.json'
    data_file.write_text(json.dumps({'rules': [{
        'id': 'paper.style.abstract-verbs', 'kind': 'lint', 'text': 'Use verbs.', 'origin': 'test',
        'metric': {'name': 'nominal_per_k', 'section': 'abstract', 'op': '<=', 'value': 80.45}}]}))
    monkeypatch.setattr(rules_mod, 'DATA_RULES_PATH', data_file)
    rules = rules_for('paper')
    nominal = ('The utilization of regularization enables the minimization of the degradation '
               'of generalization and the stabilization of the representation.')
    verbal = ('We show that weight decay keeps small models from forgetting rare facts, '
              'and we measure how much each update moves the weights.')
    assert any('paper.style.abstract-verbs' in f for f in lint_text(rules, 'abstract', nominal))
    assert not any('paper.style.abstract-verbs' in f for f in lint_text(rules, 'abstract', verbal))


def test_no_rule_bans_calibrated_hedging():
    # The corpus shows top papers hedge slightly more than controls; no style
    # rule may forbid calibrated hedges (owner 2026-11-18: no fences, but careful wording).
    hedges = {'may', 'might', 'suggests', 'suggest', 'likely', 'appears'}
    for rule in STYLE:
        assert not hedges & {p.casefold() for p in rule.get('phrases') or []}, rule['id']
