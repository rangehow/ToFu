@pytest.mark.parametrize('outcome', ['returns', 'raises'])
def test_every_tool_batch_settles_what_its_response_started(monkeypatch, outcome):
    """The root loop's tool batch is the last chance its response's calls have to adopt."""
    from types import SimpleNamespace
    from lib.tasks_pkg import persistence_wait
    from lib.tasks_pkg.orchestrator import _root_agent_loop
    from lib.tools import registry
    settled = []
    monkeypatch.setattr(registry, 'settle_stream_starts', settled.append)
    monkeypatch.setattr(persistence_wait, 'checkpoint_invocation', lambda *a, **k: None)

    def dispatch(*args, **kwargs):
        if outcome == 'raises':
            raise RuntimeError('tool batch failed')
        return False
    monkeypatch.setattr(_root_agent_loop, 'run_tool_dispatch', dispatch)
    task = {'id': 'coordinator-task'}
    hooks = _root_agent_loop._RootLoopHooks(SimpleNamespace(
        task=task, state=SimpleNamespace(), messages=[], all_search_results_text=[], tid='t', cfg={},
        project_path=None, project_enabled=False, tool_list=[]))
    hooks.round_context = {'stream_accumulator': SimpleNamespace(announced_tc_map={})}
    if outcome == 'raises':
        with pytest.raises(RuntimeError):
            hooks.execute_tools(0, [])
    else:
        hooks.execute_tools(0, [])
    assert settled == [task]
