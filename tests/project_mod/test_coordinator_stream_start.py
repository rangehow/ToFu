def _sse(protocol_calls):
    """OpenAI chat-completions frames: each call's header, then its arguments in two fragments."""
    frames = []
    for index, (call_id, arguments) in enumerate(protocol_calls):
        text = json.dumps(arguments)
        frames.append([{'index': index, 'id': call_id, 'type': 'function',
                        'function': {'name': 'delegate_project_work', 'arguments': ''}}])
        frames.append([{'index': index, 'function': {'arguments': text[:len(text) // 2]}}])
        frames.append([{'index': index, 'function': {'arguments': text[len(text) // 2:]}}])
    return ['data: ' + json.dumps({'id': 'resp', 'object': 'chat.completion.chunk', 'model': 'gpt-4o',
                                   'choices': [{'index': 0, 'delta': {'tool_calls': delta}}]})
            for delta in frames]


def _provider_stream(on_tool_call_ready):
    from lib.llm._sse_core import SSEAccumulator, prepare_request
    plan = prepare_request({'model': 'gpt-4o', 'stream': True, 'max_tokens': 64,
                            'messages': [{'role': 'user', 'content': 'plan'}]},
                           base_url='https://example.invalid/v1', api_key='test-key', api_protocol='openai')
    return SSEAccumulator(plan.body, plan.trace_id, plan.raw_dumper, plan.wire_translator, plan.t0,
                          on_tool_call_ready=on_tool_call_ready)


def _started(r):
    return {birth.assignment_id: birth for birth in coordinator_births.recorded(r.task)}


def _stream_one_call(r, arguments, call_id='call-1'):
    stream = _provider_stream(r.accumulator.on_tool_call_ready)
    for line in _sse([(call_id, arguments)]):
        stream.feed_line(line)
    stream.fire_final_tool_callback()
    assert len(_started(r)) == 1, 'the call starts while its response streams'
    return next(iter(_started(r).values()))


def test_the_first_delegation_starts_before_the_second_calls_arguments_finish(streaming):
    r = streaming
    stream = _provider_stream(r.accumulator.on_tool_call_ready)
    lines = _sse([('call-1', r.args), ('call-2', r.second)])
    # Call 1 complete; call 2's header and half its arguments have streamed.
    for line in lines[:5]:
        stream.feed_line(line)
    assert r.entered.wait(10), 'call 1 Worker birth is running while call 2 still streams'
    assert [birth.title for birth in _started(r).values()] == [r.args['title']]
    stream.feed_line(lines[5])
    stream.fire_final_tool_callback()
    assert sorted(birth.title for birth in _started(r).values()) == sorted([r.args['title'], r.second['title']])

    # The response ended: its ordinary dispatch adopts both births, never a second Worker.
    first, second = r.call('delegate_project_work', **r.args), r.call('delegate_project_work', **r.second)
    assert {first['assignment_id'], second['assignment_id']} == set(_started(r))
    r.release.set()
    r.settle()
    settle_stream_starts(r.task)
    assert len(r.created) == len(r.calls) == 2
    assert not any(row['grant']['revoked'] for row in r.c.repo.list())


@pytest.mark.parametrize('when', ['born', 'in_flight'])
def test_a_discarded_response_withdraws_what_it_started(streaming, when):
    """A response that never reaches its dispatch (discarded, regenerated by the provider, or
    refused before its handler) adopts nothing: the next settlement cancels its Worker."""
    r = streaming
    birth = _stream_one_call(r, r.args)
    if when == 'born':
        r.release.set()
        r.settle()
        assert not r.c.repo.read(birth.assignment_id)['grant']['revoked']
    settle_stream_starts(r.task)
    r.release.set()
    r.settle()
    assert r.c.repo.read(birth.assignment_id)['grant']['revoked']
    # The owner never saw this delegation; its views do not list it either.
    assert 'starting_workers' not in r.call('get_project_workers')


def test_a_stop_while_streaming_leaves_no_worker(streaming):
    r = streaming
    birth = _stream_one_call(r, r.args)
    r.release.set()
    r.settle()
    r.task['aborted'] = True
    # The attempt's model loop ends on Stop; its settlement runs in _run's finally.
    settle_stream_starts(r.task)
    assert r.c.repo.read(birth.assignment_id)['grant']['revoked']


def test_a_birth_stopped_before_it_began_never_starts_a_worker(streaming):
    r = streaming
    birth = _stream_one_call(r, r.args)
    assert r.entered.wait(10)
    r.task['aborted'] = True
    settle_stream_starts(r.task)
    r.release.set()
    r.settle()
    assert birth.failure is not None and not r.calls and not r.c.repo.list()


def test_a_regenerated_response_replays_the_key_and_creates_no_duplicate(streaming):
    r = streaming
    birth = _stream_one_call(r, r.args)
    r.call('delegate_project_work', **r.args)
    r.release.set()
    r.settle()
    settle_stream_starts(r.task)
    # A regenerate is a new task of the same request: its own births, the same key.
    r.task.pop(coordinator_births.BIRTHS_KEY)
    r.accumulator = StreamingToolAccumulator(r.task, '/project')
    again = _stream_one_call(r, r.args, call_id='call-regenerated')
    assert again.assignment_id == birth.assignment_id
    assert r.call('delegate_project_work', **r.args)['assignment_id'] == birth.assignment_id
    r.settle()
    settle_stream_starts(r.task)
    assert len(r.created) == len(r.calls) == 1
    assert not r.c.repo.read(birth.assignment_id)['grant']['revoked']


def test_a_regenerate_after_withdrawal_reuses_the_cancelled_key_and_says_so(streaming):
    r = streaming
    birth = _stream_one_call(r, r.args)
    r.release.set()
    r.settle()
    settle_stream_starts(r.task)
    r.task.pop(coordinator_births.BIRTHS_KEY)
    r.call('delegate_project_work', **r.args)
    r.settle()
    awaited = r.call('await_project_workers', assignment_ids=[birth.assignment_id], timeout_seconds=0)
    assert len(r.created) == len(r.calls) == 1, 'no duplicate Worker'
    assert r.c.repo.read(birth.assignment_id)['grant']['revoked']
    row, = awaited['workers']
    assert row['status'] == 'failed_to_start' and row['error']['code'] == 'delegation_cancelled', awaited
    assert 'new idempotency_key' in row['error']['recovery']


